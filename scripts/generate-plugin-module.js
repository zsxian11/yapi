const fs = require('fs');
const path = require('path');
const commonLib = require('../common/plugin.js');

let nullableConfig = null;
try {
  nullableConfig = require('../config.json');
} catch (ignore) {
}

function createImport(plugin, pathAlias) {
  const options = plugin.options ? JSON.stringify(plugin.options) : 'null';
  let importPath;
  if (pathAlias === 'node_modules') {
    importPath = `yapi-plugin-${plugin.name}/client.js`;
  } else {
    importPath = `${pathAlias}/yapi-plugin-${plugin.name}/client.js`;
  }
  const varName = `plugin_${plugin.name.replace(/-/g, '_')}`;
  return {
    importLine: `import * as ${varName} from '${importPath}';`,
    entryLine: `"yapi-plugin-${plugin.name}": { module: ${varName}.default || ${varName}, options: ${options} }`
  };
}

function initPlugins() {
  let configPlugin = [];
  if (nullableConfig && nullableConfig.plugins) {
    configPlugin = nullableConfig.plugins;
  }
  const systemConfigPlugin = require('../common/config.js').exts;

  const imports = [];
  const entries = [];

  if (configPlugin && Array.isArray(configPlugin) && configPlugin.length) {
    configPlugin = commonLib.initPlugins(configPlugin, 'plugin');
    configPlugin.forEach(plugin => {
      if (plugin.client && plugin.enable) {
        const { importLine, entryLine } = createImport(plugin, 'node_modules');
        imports.push(importLine);
        entries.push(entryLine);
      }
    });
  }

  const initializedSystemPlugins = commonLib.initPlugins(systemConfigPlugin, 'ext');
  initializedSystemPlugins.forEach(plugin => {
    if (plugin.client && plugin.enable) {
      const { importLine, entryLine } = createImport(plugin, 'exts');
      imports.push(importLine);
      entries.push(entryLine);
    }
  });

  const content = [
    '// Auto-generated by scripts/generate-plugin-module.js — do not edit',
    ...imports,
    '',
    'export default {',
    entries.join(',\n'),
    entries.length ? '' : '',
    '};',
    ''
  ].join('\n');

  fs.writeFileSync(path.join(__dirname, '../client/plugin-module.js'), content);
}

initPlugins();
